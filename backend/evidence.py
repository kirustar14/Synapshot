"""The Evidence drawer: what the model rests on, with the live numbers beside it.

The prose comes from `docs/RESEARCH.md`, parsed rather than copied. A second copy in
Python would drift from the document within a week, and the one thing this drawer must
not do is show a claim the research file no longer makes.

The numbers come from the fit as it is right now: the cohort's parameter recovery, its
coverage, how many receptor maps actually loaded, how many of the sample pack's fields
the extractor got. Every one of them is read at request time.

Never hide a weak number. A claim tagged "check this" is shown with that tag, a coverage
below target is shown as below target, and an effect whose interval includes zero is said
to include zero. The drawer is only worth having if a sceptical reader finds the weak
parts in it faster than they would by reading the code.
"""

import re

import numpy as np

from .config import ROOT

DOC = ROOT / "docs" / "RESEARCH.md"

# A claim block in the document: "**Claim.** ..." then optional "**Source.** ..." then a
# line starting with the tag.
#
# The tag is written several ways in the document and all of them have to match:
# "**verified.**", "**verified**", "**check this, and this one needs a clinician.**".
# The first version of this pattern required exactly "**verified**" and silently matched
# almost nothing, so every claim came back untagged and the drawer showed 4 of 24 tags.
TAG = re.compile(r"^\*\*(verified|check this)\b[^*]*\*\*", re.I)


def _blocks(text: str) -> list[dict]:
    """Every claim in the document, with its section, source and tag."""
    out: list[dict] = []
    section = ""
    current: dict | None = None

    def flush() -> None:
        nonlocal current
        if current and current.get("claim"):
            out.append(current)
        current = None

    for raw in text.splitlines():
        line = raw.rstrip()
        if line.startswith("## "):
            flush()
            section = line[3:].strip()
            continue
        if line.startswith("**Claim"):
            flush()
            current = {"section": section, "claim": _strip(line), "source": "",
                       "tag": "", "detail": ""}
            continue
        if current is None:
            continue
        if line.startswith("**Source."):
            current["source"] = _strip(line)
            continue
        hit = TAG.match(line)
        if hit:
            current["tag"] = hit.group(1).lower()
            current["detail"] = _strip(line)
            continue
        if line.strip() and current.get("tag"):
            current["detail"] = (current["detail"] + " " + line.strip()).strip()
        elif line.strip() and current.get("source"):
            current["source"] = (current["source"] + " " + line.strip()).strip()
        elif line.strip():
            current["claim"] = (current["claim"] + " " + line.strip()).strip()
    flush()
    return out


def _strip(line: str) -> str:
    """One document line without its bold label."""
    return re.sub(r"^\*\*[^*]+\*\*\.?\s*", "", line).strip()


def limits(text: str) -> list[str]:
    """The numbered honest limits block, as a list."""
    try:
        tail = text.split("## Honest limits", 1)[1]
    except IndexError:
        return []
    out = []
    for chunk in re.split(r"\n(?=\d+\. )", tail):
        got = chunk.strip()
        if not re.match(r"^\d+\. ", got):
            continue
        body = re.sub(r"^\d+\. ", "", got)
        out.append(" ".join(body.split()))
    return out


def claims() -> list[dict]:
    """Every claim in docs/RESEARCH.md, in document order."""
    if not DOC.exists():
        return []
    return _blocks(DOC.read_text())


def numbers() -> list[dict]:
    """The live validation numbers, read from the fit as it stands.

    Each one carries whether it is at target and the sentence that says what it means.
    `ok=False` is not hidden: a coverage below target is the most informative thing on
    this panel.
    """
    from .twin import intervention, population

    out: list[dict] = []

    cohort = population.load()
    if cohort is not None:
        cov = [float(c["cov"]) for c in (cohort.get("coverage") or []) if c.get("cov") is not None]
        if cov:
            last = cov[-1]
            out.append({
                "name": "Forecast band coverage",
                "value": round(last, 3),
                "target": 0.8,
                "ok": last >= 0.75,
                "unit": "share of weeks inside the 80% band",
                "say": ("The 80% band should contain the truth about 80% of the time. "
                        f"Across the cohort's latest week it contains it {last:.0%} of "
                        "the time."),
                "caveat": "Measured on synthetic patients generated by the same model "
                          "family that is fitting them, which is the easiest possible "
                          "test.",
            })

        ks_true = np.asarray(cohort.get("k_true") or [], dtype=float)
        ks_est = np.asarray(cohort.get("k_est") or [], dtype=float)
        if ks_true.size and ks_true.size == ks_est.size:
            good = np.isfinite(ks_true) & np.isfinite(ks_est)
            if good.sum() > 2:
                r = float(np.corrcoef(ks_true[good], ks_est[good])[0, 1])
                err = float(np.abs(ks_true[good] - ks_est[good]).mean())
                out.append({
                    "name": "Recovery rate recovery",
                    "value": round(r, 3),
                    "target": 0.7,
                    "ok": r >= 0.7,
                    "unit": f"correlation of true and fitted k over {int(good.sum())} patients",
                    "say": (f"Fitted recovery rate correlates {r:.2f} with the true one, "
                            f"mean absolute error {err:.3f}."),
                    "caveat": "The truth here is the generator's own parameter, so this "
                              "measures whether the filter can invert the simulator.",
                })

        for eff in cohort.get("effects") or []:
            lo, hi = float(eff["lo"]), float(eff["hi"])
            spans = lo <= 0.0 <= hi
            out.append({
                "name": f"Population effect: {eff['name']}",
                "value": round(float(eff["est"]), 3),
                "interval": [round(lo, 3), round(hi, 3)],
                "target": None,
                "ok": not spans,
                "unit": "posterior mean with 90% interval",
                "say": (f"Estimated {float(eff['est']):+.3f}, interval "
                        f"[{lo:+.3f}, {hi:+.3f}]"
                        + (", which includes zero." if spans else ", which excludes zero.")),
                "caveat": ("An interval that includes zero means this covariate's effect "
                           "is not distinguishable from nothing in this cohort."
                           if spans else
                           "The true value is known here because the cohort is generated."),
            })

    rec = intervention.receptors()
    real = len(rec.get("tracers") or {})
    total = len(rec.get("names") or [])
    out.append({
        "name": "Receptor maps loaded from real data",
        "value": real,
        "target": total,
        "ok": real == total,
        "unit": f"of {total} targets",
        "say": (f"{real} of {total} receptor and transporter maps are real PET or SPECT "
                "group averages." if real else
                "No receptor map loaded from real data. Every one is a smooth random "
                "stand-in and the drug viewer means nothing."),
        "caveat": ("Group averages from healthy volunteers, not this patient's receptors."
                   if real else
                   "Set OFFLINE=0 and make sure neuromaps is installed."),
    })
    if rec.get("stand_in"):
        out[-1]["detail"] = "Stand-ins: " + ", ".join(rec["stand_in"])

    return out


def ingest_score() -> dict | None:
    """How much of the sample pack's answer key the built-in extractor reads.

    Run on request, with the model switched off, because the number that belongs on this
    panel is the one a laptop with no API key gets.
    """
    from .ingest import read as readmod
    from .ingest import run as ingestrun

    files = ingestrun.sample_files()
    want = ingestrun.expected()
    if not files or not want:
        return None

    # Switching the model off has to be done on the resolved config, not on the
    # environment: `cfg.mock_llm` is a dataclass field read once at import, so setting
    # MOCK_LLM here would do nothing and this panel would quietly report Gemini's score
    # under a label that says "with no API key".
    from .config import cfg
    from .ingest import extract as extractmod

    had = cfg.mock_llm
    cfg.mock_llm = True
    try:
        got, info = extractmod.run(readmod.many(files))
    finally:
        cfg.mock_llm = had

    fields = got.fields()
    hit, miss = [], []
    for key, value in want.items():
        if key.startswith("_"):
            continue
        field = fields.get(key)
        have = getattr(field, "value", None) if field else None
        if key == "medications":
            have = [m.name for m in (have or [])]
        if _same(value, have):
            hit.append(key)
        else:
            miss.append(key)

    total = len(hit) + len(miss)
    return {
        "name": "Document extraction accuracy",
        "value": round(len(hit) / total, 3) if total else 0.0,
        "target": 0.9,
        "ok": total > 0 and len(hit) / total >= 0.9,
        "unit": f"{len(hit)} of {total} fields on the sample pack",
        "say": (f"The built-in extractor reads {len(hit)} of {total} fields correctly "
                f"with no API key ({info.get('how')})."),
        "caveat": ("Missed: " + ", ".join(miss) if miss else "")
                  or "Scored against an answer key written by the same generator that "
                     "wrote the documents, so it measures reading, not clinical judgement.",
    }


def _same(want, have) -> bool:
    """Whether an extracted field matches the answer key. Same rule as the test."""
    if isinstance(want, float):
        return isinstance(have, (int, float)) and abs(float(have) - want) < 0.051
    if isinstance(want, list):
        return set(str(x).lower() for x in want) <= set(str(x).lower() for x in (have or []))
    if want is None or have is None:
        return want == have
    return str(want).strip().lower()[:50] == str(have).strip().lower()[:50]


def payload() -> dict:
    """Everything the Evidence drawer shows."""
    text = DOC.read_text() if DOC.exists() else ""
    got = claims()
    live = numbers()
    score = ingest_score()
    if score is not None:
        live.append(score)
    weak = [n for n in live if not n["ok"]]
    return {
        "ok": True,
        "claims": got,
        "sections": list(dict.fromkeys(c["section"] for c in got if c["section"])),
        "counts": {
            "verified": sum(1 for c in got if c["tag"] == "verified"),
            "check_this": sum(1 for c in got if c["tag"] == "check this"),
        },
        "numbers": live,
        "weak": [n["name"] for n in weak],
        "limits": limits(text),
        "doc": "docs/RESEARCH.md",
        "note": ("Every claim carries whether anybody checked it. A number below its "
                 "target is shown as below its target: there is no state of this panel "
                 "that hides a weak result."),
    }
