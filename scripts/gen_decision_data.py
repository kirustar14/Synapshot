"""Generate synthetic decision traces for the open source decision model.

    python scripts/gen_decision_data.py --patients 200

Every patient is generated by the same code the app uses, with the latent truth known. The
labels are therefore oracle labels, not human annotations, and the dataset card says so.
No real patient data is involved. Nothing here should ever be pointed at a real record.

Two decision points per week: after the symptom block, and after the ocular block. Each
example carries the evidence state, a typed answer, and the heuristic's own ranking so a
GRPO reward has something honest to compare against.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.agent import adaptive  # noqa: E402
from backend.data import synthetic as syn  # noqa: E402
from backend.features import sem as semmod  # noqa: E402
from backend.twin import enkf  # noqa: E402

DOMAIN = {
    "pursuit_gain": "ocular",
    "saccade_latency": "ocular",
    "antisaccade_err": "ocular",
    "bcea": "ocular",
    "speech_rate": "speech",
    "recall_delayed": "memory",
    "symptom_total": "symptom",
}
DRIFT = ["worse", "stable", "better"]
DOMAINS = ["ocular", "speech", "memory", "symptom", "none"]


def _onehot(index: int, size: int, high: float = 0.7) -> list[float]:
    """A soft label: confident, not absurdly so. Calibration, not certainty."""
    rest = (1.0 - high) / max(1, size - 1)
    return [round(high if i == index else rest, 4) for i in range(size)]


def _labels(state: dict, delta_symptom: float) -> dict:
    """The oracle answer for one decision point."""
    z = delta_symptom / max(semmod.sem("symptom_total"), 1e-6)
    drift = "worse" if z > 1.0 else ("better" if z < -1.0 else "stable")
    worst, best = "none", 0.0
    for key, value in (state.get("residuals") or {}).items():
        mag = abs(float(value))
        if mag > best and key in DOMAIN:
            best, worst = mag, DOMAIN[key]
    if best < 0.5:
        worst = "none"
    got = adaptive.heuristic(state)
    return {
        "drift": drift,
        "worst_domain": worst,
        "next_oracle": got["next"],
        "gain": got.get("scores", {}),
        "minutes": {b: adaptive.BLOCKS[b]["minutes"] for b in adaptive.ORDER},
        "banned": False,
        "p": {
            "drift": _onehot(DRIFT.index(drift), len(DRIFT)),
            "worst_domain": _onehot(DOMAINS.index(worst), len(DOMAINS)),
        },
    }


def _assistant(labels: dict) -> str:
    return json.dumps({"p": labels["p"], "next": labels["next_oracle"]}, sort_keys=True)


def _sft(state: dict, labels: dict) -> dict:
    return {
        "messages": [
            {"role": "system", "content": adaptive.SYSTEM},
            {"role": "user", "content": json.dumps(state, sort_keys=True)},
            {"role": "assistant", "content": _assistant(labels)},
        ]
    }


def _grpo(state: dict, labels: dict) -> dict:
    return {"prompt": json.dumps(state, sort_keys=True), "answer": json.dumps(labels, sort_keys=True)}


def run(patients: int, weeks: int, seed: int) -> dict:
    eff = syn.cohort_effects(seed=1)
    rows: list[tuple[dict, dict]] = []
    for i in range(patients):
        pat = syn.make_patient(3000 + i, eff=eff)
        geno = pat["alleles"]
        state = enkf.init(np.random.default_rng(7000 + i), geno, float(pat["zbio"]),
                          pat["sex"], pat["d0_true"])
        poor = i % 7 == 0
        previous = None
        for week in range(weeks + 1):
            truth = pat["truth"][week]
            out = enkf.step(state, week, truth, flash_ok=not poor, seed=i)
            total = float(truth.get("symptom_total") or 0.0)
            delta = 0.0 if previous is None else total - previous
            previous = total
            base = {
                "week": week,
                "drift_z": round(float(out["drift_z"]), 2),
                "symptom_total": round(total, 1),
                "symptom_jump": round(delta, 1),
                "quality_ok": not poor,
                "residuals": {k: round(float(v), 2) for k, v in out["resid"].items()},
            }
            for done in (["symptoms"], ["symptoms", "ocular"]):
                remaining = [b for b in adaptive.ORDER if b not in done]
                if not remaining:
                    continue
                point = {**base, "done": done, "remaining": remaining}
                rows.append((point, _labels(point, delta)))
        if (i + 1) % 25 == 0:
            print(f"  {i + 1}/{patients} patients, {len(rows)} decision points")
    return {"rows": rows}


def write(rows: list[tuple[dict, dict]], out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    cut_a = int(len(rows) * 0.8)
    cut_b = int(len(rows) * 0.9)
    parts = {"train": rows[:cut_a], "val": rows[cut_a:cut_b], "test": rows[cut_b:]}
    counts = {}
    for name, part in parts.items():
        with (out / f"{name}.jsonl").open("w", encoding="utf-8") as fh:
            for state, labels in part:
                fh.write(json.dumps(_sft(state, labels), sort_keys=True) + "\n")
        with (out / f"{name}_grpo.jsonl").open("w", encoding="utf-8") as fh:
            for state, labels in part:
                fh.write(json.dumps(_grpo(state, labels), sort_keys=True) + "\n")
        counts[name] = len(part)
    return counts


def card(out: Path, counts: dict) -> None:
    text = f"""# Synapshot decision traces

Synthetic only. No human data, no PHI, no clinical record has been near this dataset.

Generated by `scripts/gen_decision_data.py` from the same synthetic patient generator the
app uses, with the latent recovery parameters known. The labels are oracle labels from
that generator, not clinician annotations.

- train {counts.get('train', 0):,} / val {counts.get('val', 0):,} / test {counts.get('test', 0):,}
- `train.jsonl`, `val.jsonl`, `test.jsonl`: chat SFT rows, system + state + typed JSON answer
- `*_grpo.jsonl`: `prompt` and `answer` columns for GRPO, with the heuristic's gain and
  minutes per block so a reward can score a choice without re-running the simulator
- answer schema: `p.drift` is [worse, stable, better], `p.worst_domain` is
  [ocular, speech, memory, symptom, none], `next` is a block or stop
- safety and calibration blocks are never candidates

Known limits: the labels come from the generator that the downstream filter also assumes,
so this measures the pipeline and the policy, not clinical validity. The heuristic's gain
is an information-per-minute proxy, not a measured psychometric quantity.
"""
    (out / "README.md").write_text(text, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--patients", type=int, default=200)
    ap.add_argument("--weeks", type=int, default=12)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default=str(ROOT / "data" / "decision"))
    args = ap.parse_args()

    got = run(max(1, args.patients), max(1, args.weeks), args.seed)
    out = Path(args.out)
    counts = write(got["rows"], out)
    card(out, counts)
    print("")
    print(f"  wrote {len(got['rows']):,} decision points to {out}")
    for name, n in counts.items():
        print(f"    {name:5s} {n:,}")
    print(f"  system prompt is {len(adaptive.SYSTEM)} chars")
    print(f"  mean answer length {round(sum(len(_assistant(l)) for _, l in got['rows']) / max(1, len(got['rows'])), 1)} chars")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
